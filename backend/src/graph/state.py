from typing import TypedDict, List, Dict, Any

class FundState(TypedDict):
    watchlist: List[str]
    portfolio_balance: float
    total_portfolio_value: float
    current_holdings: Dict[str, Any]
    daily_news: Dict[str, str]
    news_summary: str
    trade_proposals: List[Dict[str, Any]]     # Raw ideas generated by the LLM
    validated_orders: List[Dict[str, Any]]    # Sanitized, risk-checked orders ready for Alpaca
    audit_log: List[str]                      # Log of clamped or rejected actions